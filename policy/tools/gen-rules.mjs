// Writes src/rules.rs from chain/rules.json, so the policy embeds exactly the
// numbers the rules file holds. `cargo test` fails if the two disagree.
//
//   node tools/gen-rules.mjs
import { readFileSync, writeFileSync } from "node:fs";

const rules = JSON.parse(readFileSync(new URL("../../chain/rules.json", import.meta.url), "utf8"));
const grid = rules.grid;
const prices = Array.from({ length: grid }, () => new Array(grid).fill(0));
for (const [key, price] of Object.entries(rules.lotPrices)) {
  const [x, y] = key.split(",").map(Number);
  if (!(Number.isInteger(price) && price > 0) || !(x >= 0 && x < grid && y >= 0 && y < grid)) {
    throw new Error(`bad lot ${key}: ${price}`);
  }
  prices[y][x] = price;
}

const rows = prices.map((row) => `    [${row.join(", ")}],`).join("\n");
const source = `// Generated by tools/gen-rules.mjs from chain/rules.json. Do not edit.
// Regenerate with \`node tools/gen-rules.mjs\`; \`cargo test\` checks it.

/// Width and height of the city grid, in tiles.
pub const GRID: usize = ${grid};
/// A coordinate that is a multiple of this is a street.
pub const STREET_EVERY: u64 = ${rules.streetEvery};
/// The burn for the 2nd floor; each later floor multiplies it by \`FLOOR_GROWTH\`.
pub const FLOOR_BASE: u64 = ${rules.floorBase};
pub const FLOOR_GROWTH: u64 = ${rules.floorGrowth};
pub const MAX_FLOORS: u64 = ${rules.maxFloors};
/// How far a changed \`at\` may be from the block's timestamp, in ms.
pub const TIME_WINDOW_MS: u64 = ${rules.timeWindowMs};
pub const BRAND_MAX_BYTES: usize = ${rules.brandMaxBytes};
pub const USER_MAX_BYTES: usize = ${rules.userMaxBytes};
/// The burn address: coin credited to it never moves.
pub const BURN: &[u8] = b"${rules.burn}";

/// Each lot's claim price, \`LOT_PRICES[y][x]\`; 0 where the tile is not a lot.
pub const LOT_PRICES: [[u64; GRID]; GRID] = [
${rows}
];
`;
writeFileSync(new URL("../src/rules.rs", import.meta.url), source);
console.log(`wrote src/rules.rs: ${Object.keys(rules.lotPrices).length} lots`);
